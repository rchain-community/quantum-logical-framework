def orbit(c: float, p: int) -> float:
    x = 0.0
    for _ in range(p):
        x = x * x + c
    return x


def real_centers(period_max: int = 8, steps: int = 6000) -> dict[int, list[float]]:
    """Real superstable parameters of minimal period <= period_max (f_c^p(0) = 0)."""
    grid = [-2.0 + 2.25 * i / steps for i in range(steps + 1)]
    roots: dict[int, list[float]] = {}
    for p in range(1, period_max + 1):
        found: list[float] = []
        for a, b in zip(grid, grid[1:]):
            fa, fb = orbit(a, p), orbit(b, p)
            if fa == 0.0:
                found.append(a)
            if fa * fb < 0.0:
                lo, hi = a, b
                for _ in range(60):
                    mid = 0.5 * (lo + hi)
                    if orbit(lo, p) * orbit(mid, p) <= 0.0:
                        hi = mid
                    else:
                        lo = mid
                found.append(0.5 * (lo + hi))
        minimal = [c for c in found
                   if all(abs(orbit(c, q)) > 1e-6 for q in range(1, p) if p % q == 0)]
        roots[p] = minimal
    return roots


def skeleton() -> None:
    rule("sec 2  THE CLOSURE SKELETON -- WHERE THE CRITICAL LOOP CLOSES EXACTLY")
    print("""
A parameter `c` is a CLOSURE EVENT when the critical loop closes exactly in p steps:
`f_c^p(0) = 0`. These are the superstable parameters -- the centres of the hyperbolic
components -- and finding them is a finite computation. Their periods are the set's
skeleton.
""")
    centers = real_centers(period_max=8)
    print(f"  {'period':>8}{'# real centres':>16}   {'centres (real axis)':<40}")
    print("  " + "-" * 68)
    for p in sorted(centers):
        cs = sorted(centers[p])
        shown = ", ".join(f"{c:+.4f}" for c in cs[:4])
        if len(cs) > 4:
            shown += ", ..."
        print(f"  {p:>8}{len(cs):>16}   {shown}")
    print("""
  The period-2^k column is the period-doubling cascade -- the skeleton the loop DNA
  `W |-> W.s.W` generates (`mandelbrot_loop_dna.py` sec 2, verified against exact Newton
  superstable parameters; `chaos_emergence.py`). The other periods are the windows
  (period 3 at c ~ -1.7549, ...), the tuned copies the renormalisation picture fills in.
  Every one is a finite closure: any way at all happens in finite time.

  So the generation is: closure events (this section) -> their bulbs -> M is the closure
  of the union. One way to generate the set, not the only way.
""")
    # the cascade is the DNA's: its exact Newton centres (mandelbrot_loop_dna.py) must
    # appear in the period columns above
    cascade = {1: 0.0, 2: -1.0, 4: -1.3107, 8: -1.38154}
    print("  the period-doubling cascade, generated by W |-> W.s.W:")
    for p, c in sorted(cascade.items()):
        near = min(centers[p], key=lambda x: abs(x - c))
        ok = abs(near - c) < 5e-3
        print(f"    period {p:>2}   centre {c:+.5f}   found {near:+.5f}   agrees: {ok}")
        assert ok


