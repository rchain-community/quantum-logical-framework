def solve_is_simplest() -> None:
    """Compose the simple mechanisms and show /solve takes the least-excursion closure."""
    rule("sec 0b  /solve TAKES THE SIMPLEST PATH")
    print("""
The two simplest mechanisms are the minimal doubler (`^ -> ^<v> | ^>v<`, the electron /
positron pair) and the splice (one more twist). Compose them into a position and ask the
substrate which closure it takes:
""")
    for position in ("^", "^^<", "^<v>+-"):
        picked = solve(position, max_depth=6)
        if not picked.get("solved"):
            continue
        if picked.get("already_closed"):
            print(f"  position {position!r:<10} already a closure  ->  "
                  f"/solve takes {picked['history']!r} (excursion "
                  f"{picked['peak_excursion']})")
            continue
        events = list(search(position, max_depth=6, absorbing=True))
        if not events:
            continue
        min_exc = min(max_excursion(r["history"]) for r in events)
        agree = picked["peak_excursion"] == min_exc
        print(f"  position {position!r:<10} closures {len(events):>3}   "
              f"least excursion {min_exc}   "
              f"/solve takes {picked['history']!r} (excursion {picked['peak_excursion']})   "
              f"agrees: {agree}")
        assert agree, (position, picked, min_exc)
    print("""
  `/solve` is the deterministic cascade least peak excursion -> shortest depth -> phase +1
  -> lexicographic. Least peak excursion is least free action -- the shallowest-horizon
  closure, the one the most listeners can hold. The generation below uses exactly this.""")


# --------------------------------------------------------------------------- #
# sec 1 -- the logical rule and the capacity-R generation
# --------------------------------------------------------------------------- #
def escape_depth(c: complex, max_steps: int = 64, radius: float = 2.0) -> int:
    """Steps until |z| > radius, or max_steps if it never leaves (the capacity horizon)."""
    z = 0j
    for n in range(1, max_steps + 1):
        z = z * z + c
        if abs(z) > radius:
            return n
    return max_steps


def capacity_generation() -> None:
    rule("sec 1  THE CAPACITY-R GENERATION M_R")
    print("""
The logical rule (`mandelbrot_loop_dna.py`):
    z |-> z^2      the itinerary is COPIED           (the angle doubles -- squaring)
    + c            ONE SPLICE TWIST                  (the parameter is one letter)
An agent of capacity R holds the closures of the critical orbit up to R steps; a state
outside |z| <= 2 cannot be held, so the orbit has left its blanket. Generate:

    M_R = { c : the critical orbit has not escaped in R steps }.

M_R shrinks with R. Measure it on a sample:
""")
    rng = random.Random(20260926)
    print(f"  {'capacity R':>12}{'fraction of sample inside M_R':>32}")
    print("  " + "-" * 44)
    prev = None
    for R in (4, 8, 16, 32, 64):
        inside = total = 0
        for _ in range(40000):
            c = complex(rng.uniform(-2.1, 0.6), rng.uniform(-1.3, 1.3))
            total += 1
            if escape_depth(c, R) >= R:
                inside += 1
        frac = inside / total
        print(f"  {R:>12}{frac:>32.4f}")
        if prev is not None:
            assert frac <= prev + 0.02          # monotone up to sampling noise
        prev = frac
    print("""
  The fraction inside falls toward the true area of M as R grows: the truncation is the
  object, the limit its rendering. Every `c` in the intersection is a parameter at which
  the agent can complete every closure the orbit presents, forever.""")


