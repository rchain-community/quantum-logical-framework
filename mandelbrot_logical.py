def render(width: int = 78, height: int = 30, R: int = 64) -> None:
    rule("sec 3  THE RENDER (one way)")
    print(f"""
M_R drawn at capacity R = {R} -- one plane of closure events:
""")
    x0, x1 = -2.1, 0.6
    y0, y1 = -1.15, 1.15
    shades = " .:-=+*#%@"
    for row in range(height):
        im = y1 - (y1 - y0) * row / (height - 1)
        line = []
        for col in range(width):
            re = x0 + (x1 - x0) * col / (width - 1)
            n = escape_depth(complex(re, im), R)
            if n >= R:
                line.append("#")
            elif n < 4:
                line.append(shades[min(len(shades) - 1, n)])
            else:
                line.append(" ")
        print("  " + "".join(line))
    print("""
  `#` is inside the capacity-R set; the ramp is escape time (the free action spent
  leaving). The picture is a rendering of the finite closure object, not the object:
  the object is the closure census of sec 1-2.""")


